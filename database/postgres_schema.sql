-- PostgreSQL schema for the FastAPI app.
-- Flask still uses database/db_schema.sql on MySQL. This file does not drop an existing database.

CREATE TYPE user_role AS ENUM ('user', 'admin');
CREATE TYPE reservation_status AS ENUM ('active', 'released', 'expired', 'error', 'deleted');
CREATE TYPE pool_node_status AS ENUM ('free', 'allocated', 'maintenance', 'error');

CREATE TABLE users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role user_role NOT NULL DEFAULT 'user',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE reservations (
    id VARCHAR(36) PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    vm_count INT NOT NULL DEFAULT 1,
    duration_minutes INT NOT NULL,
    status reservation_status NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,
    nodes JSONB,
    final_stats JSONB,
    packages JSONB,
    vm_password_encrypted VARCHAR(255)
);

CREATE TABLE pool_nodes (
    name VARCHAR(50) PRIMARY KEY,
    ip VARCHAR(15) NOT NULL,
    port INT NOT NULL,
    status pool_node_status NOT NULL DEFAULT 'free',
    owner VARCHAR(32),
    expiry DOUBLE PRECISION NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_reservation_user ON reservations(user_id);
CREATE INDEX idx_reservation_status ON reservations(status);
CREATE INDEX idx_reservation_expires_at ON reservations(expires_at);
CREATE INDEX idx_reservation_status_expires ON reservations(status, expires_at);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER users_set_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER pool_nodes_set_updated_at
    BEFORE UPDATE ON pool_nodes
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
